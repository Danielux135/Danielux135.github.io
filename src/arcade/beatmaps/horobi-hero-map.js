export function isHorobiTrack(title = '') {
    const text = normalizeTrackTitle(title);
    return text.includes('horobi no fukuin') || text.includes('滅びの福音');
}

function eventFromTuple(tuple) {
    const [t, lane4, strength, roleCode, holdMs, chord4] = tuple;
    const role = HOROBI_ROLES[roleCode] || 'vocal';
    const laneIndex = Math.max(0, Math.min(3, Number(lane4) || 0));
    const chordLaneIndex = chord4 >= 0 ? Math.max(0, Math.min(3, Number(chord4) || 0)) : null;
    return {
        t,
        sourceT: t,
        s: strength / 100,
        band: role === 'bass' ? 0 : role === 'drums' || role === 'perc' ? 2 : 1,
        role,
        laneIndex,
        laneHint: laneIndex / 3,
        chordLaneIndex,
        chordLaneHint: chordLaneIndex === null ? null : chordLaneIndex / 3,
        holdDur: holdMs > 0 ? holdMs / 1000 : 0,
        profile: 'horobiHeroV10StemMania',
        manualMap: 'horobi-hero-v10-stem-mania',
    };
}

function downsample(events, diff) {
    if (diff === 'expert') return events;
    const rank = { easy: 0, medium: 1, hard: 2 }[diff] ?? 1;
    const minGap = [0.42, 0.27, 0.16][rank];
    const keepRole = rank === 0
        ? new Set(['vocal', 'bass'])
        : rank === 1
        ? new Set(['vocal', 'lead', 'bass'])
        : new Set(['vocal', 'lead', 'bass', 'drums', 'perc', 'backing']);
    const out = [];
    const lastLane = new Map();
    for (const event of events) {
        if (!keepRole.has(event.role)) continue;
        if (rank === 0 && event.s < 0.66 && event.role !== 'vocal') continue;
        if (rank === 1 && event.s < 0.52 && (event.role === 'drums' || event.role === 'perc')) continue;
        const lane = event.laneIndex ?? Math.round((event.laneHint || 0.5) * 3);
        const last = lastLane.get(lane) ?? -99;
        if (event.t - last < minGap) continue;
        if (out.length && event.t - out[out.length - 1].t < minGap * 0.52) continue;
        out.push({
            ...event,
            holdDur: rank === 0 ? 0 : Math.min(event.holdDur || 0, rank === 1 ? 0.46 : 0.68),
            chordLaneHint: null,
            chordLaneIndex: null,
        });
        lastLane.set(lane, event.t);
    }
    return out;
}

export function getHorobiHeroEvents(diff = 'medium') {
    const events = HOROBI_HERO_V10_EXPERT.map(eventFromTuple);
    return downsample(events, diff);
}
